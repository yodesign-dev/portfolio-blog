// Ngôn ngữ giao diện trang /chill: Anh / Việt.
//
// - Mặc định theo trình duyệt: 3 ngôn ngữ ưu tiên đầu có tiếng Việt hoặc vùng Việt Nam
//   (vi, vi-VN, en-VN…) → Việt, còn lại → Anh. Người xem đổi tay ở màn chào hoặc đầu bảng
//   cài đặt thì nhớ lại ở máy đó
// - Server luôn render tiếng Anh (khớp <html lang="en">), client đổi ngay sau khi hydrate
// - Nội dung Bin nhập trong Studio (nhật ký, tên bài, tên điểm đến) và tin nhắn của
//   khách giữ nguyên như đã nhập — chỉ chữ của giao diện mới đổi theo ngôn ngữ
// - Thêm chữ mới: thêm vào `en` trước, TypeScript sẽ bắt thiếu bên `vi`

import {useSyncExternalStore} from 'react'

export type Lang = 'en' | 'vi'

const LANG_KEY = 'chill:lang'
const listeners = new Set<() => void>()
let current: Lang | null = null

function readLang(): Lang {
  if (current) return current
  let saved: string | null = null
  try {
    saved = localStorage.getItem(LANG_KEY)
  } catch {
    // Chặn storage → theo trình duyệt
  }
  if (saved === 'en' || saved === 'vi') current = saved
  else {
    const prefers = navigator.languages?.length ? navigator.languages : [navigator.language ?? 'en']
    current = prefers.slice(0, 3).some((l) => /^vi\b|-vn$/i.test(l)) ? 'vi' : 'en'
  }
  return current
}

export function setLang(lang: Lang) {
  current = lang
  try {
    localStorage.setItem(LANG_KEY, lang)
  } catch {
    // Chặn storage — chỉ đổi cho lần xem này
  }
  listeners.forEach((l) => l())
}

function subscribe(listener: () => void) {
  listeners.add(listener)
  return () => {
    listeners.delete(listener)
  }
}

export function useLang(): Lang {
  return useSyncExternalStore(subscribe, readLang, () => 'en')
}

export function useT() {
  return STRINGS[useLang()]
}

